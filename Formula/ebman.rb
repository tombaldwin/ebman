      url "https://github.com/tombaldwin/ebman/releases/download/v#{version}/ebman-v#{version}-x86_64-apple-darwin.tar.gz"
      sha256 "35d1e5c5cd27c4522f155ed0401e51d7c820116e3e15f4a0825b08bcd53bae86"
