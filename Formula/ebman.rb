      url "https://github.com/tombaldwin/ebman/releases/download/v#{version}/ebman-v#{version}-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "36a132fcd9c90df7a7fdea551fa42b15af6a382c8193d5a81bfb3aa285765a1f"
